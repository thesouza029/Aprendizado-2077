export function techLabel(slug: string, locale: string): string {
  const label = labels[slug];
  if (!label) return slug.charAt(0).toUpperCase() + slug.slice(1);
  if (typeof label === "string") return label;
  return locale === "en" ? label.en : label.pt;
}
